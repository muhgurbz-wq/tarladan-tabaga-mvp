import fs from 'node:fs';
import vm from 'node:vm';
const html=fs.readFileSync('experiments/index.html','utf8');
const manifest=JSON.parse(fs.readFileSync('experiments/manifest.webmanifest','utf8'));
const sw=fs.readFileSync('experiments/sw.js','utf8');
const checks=[];const check=(n,o)=>{checks.push([n,!!o]);if(!o)process.exitCode=1};
check('20 products present',(html.match(/\['[^']+','[^']+','[^']+'/g)||[]).length>=20);
check('Working workspace exists',html.includes('id="preview"')&&html.includes('function generate()'));
check('Detail accordions exist',html.includes('class="accWrap"')&&html.includes('class="acc"')&&html.includes('class="accBody"'));
check('Output copy exists',html.includes('navigator.clipboard.writeText'));
check('UTF-8 HTML download exists',html.includes('downloadHTML()')&&html.includes('charset=utf-8')&&html.includes('Date.now()'));
check('PDF print exists',html.includes('printPDF()')&&html.includes('.print()'));
check('Share exists',html.includes('navigator.share'));
check('Install prompt handled',html.includes('beforeinstallprompt')&&html.includes('installPrompt')&&html.includes('.prompt()'));
check('Install fallback modal exists',html.includes('id="installModal"')&&html.includes('Android')&&html.includes('iPhone / iPad')&&html.includes('Windows / macOS'));
check('Install state handled',html.includes('display-mode: standalone')||html.includes('navigator.standalone'));
check('Service worker registered',html.includes("navigator.serviceWorker.register('sw.js'"));
check('Lead form product specific',html.includes('formsubmit.co')&&html.includes('name="Ürün"')&&html.includes('Erişim talebi'));
check('Manifest standalone',manifest.display==='standalone');
check('Manifest id',typeof manifest.id==='string'&&manifest.id.length>0);
check('Manifest scoped',manifest.scope==='./');
check('SW force upgrade',sw.includes('skipWaiting')&&sw.includes('clients.claim'));
check('Old caches removed',sw.includes('caches.delete'));
check('Navigation network first',sw.includes("req.mode==='navigate'")&&sw.includes("cache:'no-store'"));
const scripts=[...html.matchAll(/<script>([\s\S]*?)<\/script>/g)].map(m=>m[1]);
check('Inline JavaScript parses',scripts.length>0&&scripts.every(s=>{try{new vm.Script(s);return true}catch(e){console.error(e);return false}}));
for(const [n,o] of checks)console.log(`${o?'PASS':'FAIL'}  ${n}`);if(process.exitCode)throw new Error('Smoke test failed');console.log(`PASS  ${checks.length}/${checks.length} checks`);
